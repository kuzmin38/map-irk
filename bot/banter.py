"""Живая реакция Люси в рабочем чате.

Заказчик: «разрешим ей больше активничать в чате, пусть разряжает обстановку».
Мера тут важнее остроумия: бот, вставляющий слово в каждое сообщение, из чата
улетает первым — и вместе с ним всё, что он собирает. Поэтому реплика
короткая, редкая и только на понятный повод: поздоровались, поблагодарили,
закрыли работу, устали, мороз, пятница.

Реплики свои, не от модели: в рабочем чате важнее предсказуемость и
мгновенный ответ, чем свежесть шутки. Молчит по аварийным сообщениям —
там не до веселья.

Главное правило заготовок: реплика ничего не утверждает. Стояло «Ну вот,
а говорили — до вечера» — и в чате это прочли как ссылку на чей-то срок,
которого никто не называл. Проверяется тестом: ни «говорили», ни «обещали»
в заготовках быть не должно.

Исключение одно — LETOPIS. «Записала в летопись» заказчику нравилось, и
фраза осталась, но теперь она не украшение, а сообщение по делу: Люся
говорит её только там, где запись правда легла в ленту дома. Условие
считает вызывающая сторона и передаёт в v_letopisi.
"""
import random
import re
import time

# Не чаще раза в полчаса на чат: реже — незаметно, чаще — надоедает
PAUSE = 30 * 60

TRIGGERS = [
    ('privet', re.compile(
        r'\b(доброе утро|с добрым утром|доброго утра|доброго дня|всем привет|'
        r'привет всем|здоров[оа], мужики|всем здоров|доброе утречко)\b', re.I), [
        'Доброе утро! ☀️ Пусть сегодня нигде не потечёт.',
        'Утро доброе. Кофе — и по подвалам 💪',
        'Всем доброго! Я на месте, если что — зовите.',
        'Доброе! Сегодня без аварий — я уже договорилась ☺️',
    ]),
    ('spasibo', re.compile(
        r'\b(спасибо|спс|благодар\w*|молодц[ыа]|красав\w*|от души)\b', re.I), [
        'Пожалуйста 🙂',
        'Обращайтесь. Мне-то что, я с ключом в подвал не лезу 😄',
        'Сочтёмся ☺️',
        'Всегда рада.',
    ]),
    ('pohvala', re.compile(
        r'\b(нравится|умниц\w*|умнеешь|толков\w*|соображ\w*|выруч\w*|'
        r'помощниц\w*|полезная штука)\b', re.I), [
        'Приятно слышать ☺️ Постараюсь и дальше.',
        'Спасибо! Учусь у вас.',
        'Ну вот, а меня ещё месяц назад никто и не знал 🙂',
    ]),
    ('gotovo', re.compile(
        r'\b(готово|сделал[иа]?|сделано|закрыл[иа]?|устранил[иа]?|заменил[иа]?|'
        r'запустил[иа]?|заработал[оа]?|всё работает|все работает|порядок)\b', re.I), [
        'Хорошая новость 👏',
        'Красиво сработано.',
        'Минус одна головная боль 💪',
        'Принято. Хорошая работа 👍',
    ]),
    ('ustali', re.compile(
        r'\b(устал|заколебал|задолбал|достало|тяжёлый день|тяжелый день|жесть|'
        r'капец|кошмар|сил нет|вымотал|с ног валю)', re.I), [
        'Держитесь, мужики. Смена не вечная ☕',
        'Тяжело — значит, работаем. Вечером всё это кончится.',
        'Сегодня было непросто. Завтра, надеюсь, полегче.',
        'Вы сегодня герои, без шуток.',
    ]),
    ('holod', re.compile(r'\b(мороз|холодрыг|дубак|минус \d|метел|пург)', re.I), [
        'Иркутск, что тут скажешь ❄️ Грейтесь.',
        'Главное — руки берегите, ими ещё работать.',
        'Зато трубы честно показывают, где утеплять 😅',
    ]),
    ('pyatnitsa', re.compile(r'\b(пятниц|выходн|конец недели)', re.I), [
        'Пятница — держимся, немного осталось 🙂',
        'До выходных дотерпим, а там уж как повезёт.',
    ]),
]

# Про запись — только когда запись есть. Заказчик: «Красиво, записала в
# летопись — мне нравилось». Фраза вернулась, но с условием: сообщение
# попало в ленту дома, а не просто прозвучало в чате
LETOPIS = [
    'Красиво. Записала в летопись 📒',
    'Принято, записала в летопись дома 📒',
]

# Аварийное — не повод для шуток; там Люся отвечает делом
STOP = re.compile(
    r'\b(теч|прорв|прорыв|порыв|затоп|залив|топит|подтопл|подтапл|авари|фонтан|срочно|'
    r'свищ|засор|сорвал|потоп|нет воды|нет отоплен|нет гвс|нет хвс)', re.I)

_LAST = {}     # чат → (когда, какой повод) — чтобы не повторяться


def pick(text: str, v_letopisi: bool = False):
    """Повод и реплика для сообщения, или None.

    v_letopisi — сообщение действительно легло в ленту дома. Только тогда
    Люся имеет право сказать, что записала.
    """
    if not text or STOP.search(text):
        return None
    for name, pattern, lines in TRIGGERS:
        if pattern.search(text):
            if name == 'gotovo' and v_letopisi:
                return name, random.choice(LETOPIS)
            return name, random.choice(lines)
    return None


def reply(chat_id, text: str, now: float | None = None,
          v_letopisi: bool = False) -> str | None:
    """Что ответить в чате — или None, если сейчас лучше промолчать.

    Молчит, если с прошлой реплики не прошло полчаса или повод тот же самый,
    что в прошлый раз: две одинаковые шутки подряд хуже одной.
    """
    found = pick(text, v_letopisi=v_letopisi)
    if not found:
        return None
    name, line = found
    now = time.monotonic() if now is None else now
    was_at, was_name = _LAST.get(chat_id, (None, None))
    if was_at is not None and now - was_at < PAUSE:
        return None
    if name == was_name and was_at is not None and now - was_at < PAUSE * 4:
        return None
    _LAST[chat_id] = (now, name)
    return line


def forget(chat_id=None):
    """Сброс паузы — нужен тестам и перезапуску разговора."""
    if chat_id is None:
        _LAST.clear()
    else:
        _LAST.pop(chat_id, None)
