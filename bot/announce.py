"""Объявление жильцам из наговоренного.

Заказчик наговаривает голосом: «перекрываем стояк на 65а/3 с десяти до
двух, вода будет только вечером». В домовой чат такое не выложишь — там
читают жильцы, и от тона зависит, поймут они или напишут жалобу.

Люся переписывает это деловым языком: обращение, суть, просьбы пунктами,
подпись компании. Ничего не добавляя от себя — все цифры, адреса и сроки
остаются ровно теми, что назвал человек.

Текст всегда показывается человеку до отправки. Объявление жильцам —
единственное, что уходит наружу, и цена ошибки там другая.
"""
import re

from . import ai

# «Сделай объявление жильцам», «напиши в домовой чат», «грамотным языком»
TRIGGER = re.compile(
    r'(?<![а-я])(объявлен\w*|объяв\w+|жильц\w+|домов\w+\s+чат\w*|'
    r'чат\s+дома|грамотн\w+\s+язык\w*)(?![а-я])', re.IGNORECASE)

ZADANIE = (
    'Ты — управляющая компания «Жемчужина», Иркутск. Сантехник наговорил '
    'своими словами то, что нужно сообщить жильцам дома. Составь объявление '
    'в домовой чат.\n\n'
    'Слова сантехника:\n«{text}»\n\n'
    'ПОРЯДОК, менять нельзя:\n'
    '1. «Уважаемые жильцы!»\n'
    '2. Что будет и когда — одной фразой, в будущем времени. Сначала работа, '
    'потом причина: «будет перекрыт стояк холодного водоснабжения — для '
    'замены запорной арматуры». Дату и время указывай, только если они '
    'названы; не названы — просто не пиши о них.\n'
    '3. Кого касается: «Без воды будут квартиры:» и список с новой строки. '
    'Если квартиры не названы — пропусти этот блок целиком.\n'
    '4. «Просим вас:» и просьбы списком, каждая с новой строки и с «• ». '
    'Только то, что жильцу нужно сделать. Если просьб нет — пропусти блок.\n'
    '5. Куда обращаться: «По вопросам — диспетчерская: {telefon}.» Телефон '
    'бери отсюда дословно и не меняй ни цифры. Телефона нет — блока нет.\n'
    '6. «О возобновлении подачи сообщим в этом чате.» — если речь об '
    'отключении.\n'
    '7. С новой строки: «Управляющая компания «Жемчужина»».\n\n'
    'ЗАПРЕЩЕНО:\n'
    '— выдумывать то, чего нет в словах сантехника: даты, часы, сроки, '
    'причины, номера квартир. Нет — значит, об этом молчим. Телефон бери '
    'только тот, что дан выше, другого не придумывай;\n'
    '— писать в прошедшем времени о том, что ещё предстоит: не «отключены '
    'квартиры», а «без воды будут квартиры»;\n'
    '— переносить указания, адресованные рабочим, а не жильцам: «начать '
    'проверку можно с первых этажей», «пройти по стояку снизу вверх» — это '
    'не для жильцов, такое выбрасывай;\n'
    '— канцелярит: «в связи с необходимостью проведения работ», «в целях '
    'обеспечения», «доводим до вашего сведения». Пиши по-человечески;\n'
    '— называть имена сотрудников и квартиру, где авария;\n'
    '— брань и грубость.\n\n'
    'Требования к языку: спокойно, вежливо, без заискивания. Короткие фразы. '
    'Всё объявление — не длиннее 1200 знаков.\n'
    'Верни только текст объявления, без пояснений и без кавычек вокруг него.'
)


def telefon_dispetcherskoy() -> str:
    """Телефон диспетчерской из справочника. Пусто — если не заполнен.

    Берём из справочника, а не из головы модели: выдуманный телефон в
    объявлении жильцам хуже отсутствующего.
    """
    import json
    import os
    import re as _re

    from . import houses

    try:
        put = os.path.join(houses.DATA_DIR, 'directory.json')
        with open(put, encoding='utf-8') as f:
            sections = json.load(f)['sections']
    except Exception:
        log.warning('Не удалось прочитать справочник', exc_info=True)
        return ''
    for s in sections:
        if s.get('id') != 'phones':
            continue
        m = _re.search(r'Диспетчерская:\s*([^\n]+)', s.get('text') or '')
        if not m:
            return ''
        nomer = m.group(1).strip()
        return '' if nomer.startswith('—') else nomer
    return ''


def wants_announcement(text: str) -> bool:
    return bool(text) and bool(TRIGGER.search(text))


def strip_trigger(text: str) -> str:
    """Убирает саму просьбу, оставляя то, что надо объявить."""
    out = re.sub(r'^@?люс[яеию][\s,]*', '', (text or '').strip(), flags=re.IGNORECASE)
    out = re.sub(r'(?<![а-я])(сделай|напиши|составь|подготовь|оформи|переделай)'
                 r'\s+(мне\s+)?(пожалуйста\s+)?', ' ', out, flags=re.IGNORECASE)
    out = re.sub(r'(?<![а-я])(объявлени\w*|объяв\w+)\s*(для\s+жильцов|жильцам)?',
                 ' ', out, flags=re.IGNORECASE)
    out = re.sub(r'(?<![а-я])(грамотн\w+\s+язык\w*|деловым\s+языком|'
                 r'в\s+домов\w+\s+чат\w*|в\s+чат\s+дома|для\s+жильцов|жильцам)',
                 ' ', out, flags=re.IGNORECASE)
    out = re.sub(r'[ \t]{2,}', ' ', out)
    return out.strip(' ,.;:—-')


async def sostavit(text: str, kvartiry: list | None = None) -> str | None:
    """Готовое объявление или None, если модель не ответила.

    kvartiry — список отключённых квартир из шахматки. Его модель не
    выдумывает, а получает готовым: перепутать номера здесь нельзя.
    """
    sut = strip_trigger(text)
    if kvartiry:
        spisok = ', '.join(str(k) for k in kvartiry)
        sut += (f'\n\n(Отключены квартиры: {spisok}. Перечисли их в объявлении '
                'полностью и без изменений.)')
    if len(sut) < 15:
        return None
    telefon = telefon_dispetcherskoy()
    zadanie = ZADANIE.format(text=sut, telefon=telefon) if telefon else \
        BEZ_TELEFONA.format(text=sut)
    return await ai.ask(zadanie, max_tokens=700, temperature=0.2)


# ---------- Правка готового объявления ----------

# «Убери пункт про шахту», «добавь про подъезд», «перепиши короче»
PRAVKA = re.compile(
    r'(?<![а-я])(убер\w+|удал\w+|выкин\w+|исключ\w+|добав\w+|допиш\w+|'
    r'замен\w+|помен\w+|исправ\w+|перепиш\w+|переделай|сократ\w+|'
    r'покороче|подробнее|вместо)(?![а-я])', re.IGNORECASE)

ZADANIE_PRAVKI = (
    'Ниже объявление для жильцов дома и просьба его поправить. Внеси правку '
    'и верни исправленный текст целиком.\n\n'
    'Объявление:\n«{text}»\n\n'
    'Правка: «{pravka}»\n\n'
    'Правила:\n'
    '— меняй только то, о чём просят. Остальное оставь дословно, включая '
    'номера квартир, адреса, даты и часы;\n'
    '— ничего не добавляй от себя: ни сроков, ни причин, ни обещаний;\n'
    '— сохрани строй: обращение, суть, просьбы списком, подпись компании;\n'
    '— если правка непонятна или относится не к этому тексту, верни текст '
    'без изменений;\n'
    'Верни только текст объявления, без пояснений и без кавычек вокруг него.'
)


def wants_pravka(text: str) -> bool:
    return bool(text) and bool(PRAVKA.search(text))


async def popravit(text: str, pravka: str) -> str | None:
    """Объявление с внесённой правкой. None — если модель не ответила."""
    if not text or not pravka:
        return None
    return await ai.ask(ZADANIE_PRAVKI.format(text=text, pravka=pravka.strip()),
                        max_tokens=900, temperature=0.2)


