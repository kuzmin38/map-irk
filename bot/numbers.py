# Окончание порядкового → наращение к цифре: седьмая → 7-я, седьмом → 7-м
ENDINGS = {
    'ый': 'й', 'ий': 'й', 'ой': 'й', 'ая': 'я', 'ое': 'е', 'ые': 'е',
    'ие': 'е', 'ого': 'го', 'ому': 'му', 'ым': 'м', 'им': 'м', 'ом': 'м',
    'ую': 'ю', 'ых': 'х', 'их': 'х', 'ей': 'ей', 'ем': 'м',
}
# Третий стоит особняком: мягкая основа со своими окончаниями
SOFT_ENDINGS = {
    'ий': 'й', 'ья': 'я', 'ье': 'е', 'ьего': 'го', 'ьему': 'му',
    'ьем': 'м', 'ьей': 'ей', 'ью': 'ю', 'ьи': 'и', 'ьих': 'х', 'ьим': 'м',
}


def _build() -> dict:
    """Словарь: слово → (значение, наращение или None для количественных)."""
    words = {}
    for value, forms in CARDINALS.items():
        for form in forms:
            words[form] = (value, None)
    for value, stem in ORDINAL_STEMS.items():
        for ending, suffix in ENDINGS.items():
            words[stem + ending] = (value, suffix)
        if stem == 'четвёрт':  # в речи слышится и без ё
            for ending, suffix in ENDINGS.items():
                words['четверт' + ending] = (value, suffix)
    for ending, suffix in SOFT_ENDINGS.items():
        words['трет' + ending] = (3, suffix)
    return words


WORDS = _build()

# Слова, рядом с которыми число — это номер, а не количество
ANCHORS = re.compile(
    r'^(дом\w*|д|корпус\w*|корп|стро\w+|квартир\w*|кв|подъезд\w*|под|этаж\w*|'
    r'стояк\w*|номер\w*|№)$', re.IGNORECASE)

_TOKEN = re.compile(r'\w+|[^\w\s]+|\s+')


def _street_stems() -> frozenset:
    """Основы названий улиц: «Байкальская двести тридцать семь» — тоже адрес.

    Слово «дом» в речи чаще всего опускают. Названия берём из своего же
    справочника домов и режем окончание, чтобы падеж не мешал: сказать могут
    и «на Байкальскую», и «по Байкальской».
    """
    from . import houses

    stems = set()
    for house in houses.ALL_HOUSES:
        # Отрезаем только номер дома с конца: у «4-я Советская 30» улица
        # начинается с цифры, и делением по первой цифре её теряли целиком
        street = houses._split_addr(house['address'])[0]
        for word in street.split():
            word = word.strip('-').lower()
            if len(word) >= 6:
                stems.add(word[:-2])
            elif len(word) >= 4:
                stems.add(word)
    return frozenset(stems)


# Считаем при первом обращении, а не при импорте: houses тоже обращается
# сюда на уровне модуля, и при импорте numbers первым получался замкнутый круг
_STREETS = None


def streets() -> frozenset:
    global _STREETS
    if _STREETS is None:
        _STREETS = _street_stems()
    return _STREETS


def _is_anchor(token: str) -> bool:
    return bool(ANCHORS.match(token.strip('.')))


def _is_street(token: str) -> bool:
    low = token.lower()
    return any(low.startswith(stem) for stem in streets())


def to_digits(text: str, anywhere: bool = False) -> str:
    """Переводит номера домов и квартир из слов в цифры.

    По умолчанию трогает только числа рядом со словами «дом», «квартира»,
    «подъезд», «этаж», «стояк», «корпус», «номер»: в живой речи «один раз»
    и «в первую очередь» числами не являются.

    anywhere=True — переводить любое число. Так разбираем поисковый запрос
    по адресу: там счёту взяться неоткуда, всё сказанное относится к дому.
    """
    if not text:
        return text

    tokens = _TOKEN.findall(text)
    # Индексы слов: пробелы и знаки препинания при поиске соседей пропускаем
    words = [i for i, t in enumerate(tokens) if re.match(r'\w', t)]

    i = 0
    while i < len(words):
        start = i
        value = 0
        suffix = None
        while i < len(words):
            found = WORDS.get(tokens[words[i]].lower())
            if not found:
                break
            # Число не склеивается через знаки препинания: в «квартира сорок
            # семь, второй подъезд» это два числа, а не сорок девять
            if i > start and not ''.join(tokens[words[i - 1] + 1:words[i]]).isspace():
                break
            value += found[0]
            suffix = found[1]      # наращение берём у последнего слова числа
            i += 1
        if i == start:
            i += 1
            continue

        before = tokens[words[start - 1]] if start > 0 else ''
        after = tokens[words[i]] if i < len(words) else ''
        # Улица — только перед числом: номер дома идёт после названия, а
        # «три дня на Седова» превращать в «3 дня» не нужно
        if anywhere or _is_anchor(before) or _is_anchor(after) or _is_street(before):
            tokens[words[start]] = f'{value}-{suffix}' if suffix else str(value)
            # «двести тридцать семь» становится одним «237»: лишние слова
            # убираем вместе с пробелами перед ними
            for k in range(start + 1, i):
                tokens[words[k]] = ''
                gap = words[k] - 1
                if tokens[gap].isspace():
                    tokens[gap] = ''
    return ''.join(tokens)
