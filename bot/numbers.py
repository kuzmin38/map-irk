"""Числа словами → цифрами в расшифровках речи.

Просьба проектного менеджера: в отчётах сантехников номера домов и квартир
должны стоять цифрами. Распознавание речи пишет их словами — «сорок седьмая
квартира», «Байкальская двести тридцать семь», — и такой текст неудобно
читать и невозможно искать по номеру.

Просить об этом модель ненадёжно: указание «пиши цифрами» спорит с указанием
«расшифруй дословно», и модель слушается через раз. Поэтому переводим сами,
уже после распознавания, и только рядом с техническими словами: «один раз»
и «в первую очередь» трогать нельзя.
"""
import re

