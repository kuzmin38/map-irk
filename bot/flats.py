"""Замечания по квартирам: что уже находили за этой дверью.

Костя прислал видео с подписью «71/1 105 квартира» и сказал в кадре, что
нашёл подмес. Через полгода подмес там же найдут снова — потому что забыли
перекрыть краны, — и никто не вспомнит, что это уже было.

Такие находки живут по квартирам, а не по домам: дом большой, а проблема
за конкретной дверью. Поэтому отдельная запись — адрес, квартира, что
нашли, кто и когда.

Разбираем кодом. Условий три и все обязательны: назван дом, названа
квартира, названа находка. Без любого из трёх не записываем ничего —
лучше пропустить, чем засорить.
"""
import re

# Номер квартиры: «кв. 105», «105 квартира», «105квартира», «в 105 кв»
# «кв. м» — это площадь, а не квартира: такой хвост отсекаем сразу
FLAT = re.compile(
    r'(?:(?<![а-я])кв\.?\s*(?:артир\w*)?\s*(?P<a>\d{1,4})(?![\d/])'
    r'|(?<![\d/])(?P<b>\d{1,4})\s*-?\s*(?:я|ая)?\s*'
    r'кв(?:артир\w*|\.(?!\s*м)|(?![а-яё.])))',
    re.IGNORECASE)

# Находка: физический дефект, который повторится. Список короткий и строгий —
# ложная запись здесь дороже пропуска
NAHODKA = re.compile(
    r'(?<![а-я])(подмес\w*|подмеш\w+|обратк\w+\s+ид[её]т|'
    r'теч\w+|течет|подтека\w+|подтекает|капа\w+|кап[её]ж\w*|свищ\w*|'
    r'потек\w*|пот[её]к\w*|сочит\w+|'
    r'конденсат\w*|сырост\w*|плесен\w*|грибок\w*|'
    r'засор\w*|забит\w*|не\s+уходит\s+вода|'
    r'корроз\w+|ржав\w+|гнил\w+|свищ\w*|'
    r'не\s+перекрыва\w+|не\s+держит|не\s+закрыва\w+|'
    r'нет\s+(?:крана|вентил\w+|перекрыт\w+)|'
    r'разморож\w+|замерз\w+|заморож\w+|'
    r'хомут\w*|аварийн\w+|срыв\w*|сорвал\w*)(?![а-я])',
    re.IGNORECASE)


def parse_flat(text: str, house=None):
    """Номер квартиры из сообщения. None — если не назван.

    Слово «кв» обязательно, поэтому номер дома квартирой стать не может:
    в «71/1 105 квартира» за «71» никакого «кв» не следует. Дом здесь
    ничего не решает — параметр остался для читаемости вызовов.
    """
    if not text:
        return None
    m = FLAT.search(text)
    if not m:
        return None
    nomer = m.group('a') or m.group('b')
    try:
        n = int(nomer)
    except (TypeError, ValueError):
        return None
    return n if 1 <= n <= 2000 else None


# Как эта находка называется в отчёте. Слева — то, что говорят на объекте
# и что попадает в расшифровку, справа — слово для документа.
#
# Заказчик: «Чё за течка??? Сделай, чтобы выражалась нормальными словами:
# течь!» Люся печатала находку ровно как услышала, а услышала она разговорную
# речь. Живая фраза остаётся в тексте записи целиком — здесь только термин.
TERMINY = (
    (('теч', 'потек', 'подтек', 'сочит'), 'течь'),
    (('кап',), 'капает'),
    (('свищ',), 'свищ'),
    (('подмес', 'подмеш', 'обратка ид'), 'подмес'),
    (('засор', 'забит', 'не уходит вода'), 'засор'),
    (('конденсат',), 'конденсат'),
    (('сырост',), 'сырость'),
    (('плесен', 'грибок'), 'плесень'),
    (('корроз', 'ржав'), 'коррозия'),
    (('гнил',), 'гниль'),
    (('разморож', 'замерз', 'заморож'), 'размораживание'),
    (('хомут',), 'хомут на трубе'),
    (('срыв', 'сорвал'), 'срыв'),
    (('аварийн',), 'аварийное состояние'),
    (('не перекрыва', 'не держит', 'не закрыва'), 'запорная арматура не держит'),
    (('нет крана', 'нет вентил', 'нет перекрыт'), 'нет запорной арматуры'),
)


def termin(chto: str) -> str:
    """Слово для отчёта. «Течка», сказанная на бегу, в документе — «течь»."""
    if not chto:
        return chto
    nizhe = chto.lower().replace('ё', 'е')
    for korni, slovo in TERMINY:
        if any(nizhe.startswith(k.replace('ё', 'е')) for k in korni):
            return slovo
    return nizhe


def nahodka(text: str) -> str | None:
    """Что нашли — термином, а не разговорным словом. None — находки нет."""
    if not text:
        return None
    m = NAHODKA.search(text)
    return termin(m.group(0)) if m else None


def kind_of(chto: str) -> str:
    """Ключ находки, по которому видно повтор: «засор» и «засорён» — одно."""
    chto = (chto or '').lower().replace('ё', 'е')
    return chto if ' ' in chto else chto[:5]


def parse_note(text: str, house=None):
    """(квартира, находка) или None. Нужны обе части сразу."""
    kvartira = parse_flat(text, house)
    if kvartira is None:
        return None
    chto = nahodka(text)
    if not chto:
        return None
    return kvartira, chto


def summary(text: str, limit: int = 200) -> str:
    """Короткая суть для записи: первое предложение с находкой."""
    if not text:
        return ''
    for kusok in re.split(r'(?<=[.!?])\s+|\n', text):
        if NAHODKA.search(kusok):
            return kusok.strip()[:limit]
    return text.strip()[:limit]
