"""Люся говорит о себе в женском роде.

Модель регулярно сбивается: «Понял, переписываю», «Проверил и не нашёл».
В подсказке это сказано прямо, но указание она держит через раз — а
собеседники видят это сразу и каждый раз спотыкаются.

Поэтому правим готовый ответ. Правим узко: только те формы, где Люся
говорит о себе — в начале предложения или сразу после «я». Чужие слова
трогать нельзя: «Виталя записал», «сантехник посмотрел» должны остаться.
"""
import re

# Глаголы прошедшего времени, которыми она рассказывает о своих действиях
VERBS = [
    'понял', 'записал', 'запомнил', 'проверил', 'посмотрел', 'нашёл', 'нашел',
    'сделал', 'добавил', 'обновил', 'уточнил', 'отправил', 'открыл', 'закрыл',
    'поправил', 'исправил', 'собрал', 'подготовил', 'сохранил', 'убрал',
    'создал', 'завёл', 'завел', 'передал', 'напомнил', 'подсчитал', 'посчитал',
    'смог', 'успел', 'забыл', 'ошибся', 'разобрался', 'глянул', 'заглянул',
    'увидел', 'услышал', 'принял', 'поставил', 'вписал', 'начал', 'закончил',
]
# Прилагательные и краткие формы: «готов помочь», «рад стараться»
ADJECTIVES = [
    'готов', 'рад', 'должен', 'уверен', 'согласен', 'способен', 'обязан',
    'вынужден', 'занят', 'свободен',
]

# Мужской → женский. «Нашёл» → «Нашла»: у беглой гласной своё правило
SPECIAL = {'нашёл': 'нашла', 'нашел': 'нашла', 'смог': 'смогла',
           'ошибся': 'ошиблась', 'разобрался': 'разобралась',
           'рад': 'рада', 'должен': 'должна', 'свободен': 'свободна',
           'занят': 'занята', 'завёл': 'завела', 'завел': 'завела'}


def _female(word: str) -> str:
    low = word.lower()
    fem = SPECIAL.get(low) or (low + 'а' if low in VERBS else low + 'а')
    return fem.capitalize() if word[:1].isupper() else fem


_WORDS = VERBS + ADJECTIVES
_ANY = '|'.join(_WORDS)

# Где она говорит о себе: с начала предложения, с начала строки списка или
# сразу после «я». В середине фразы почти всегда речь о человеке — «Виталя
# записал показания», «мастер посмотрел стояк», — и такое трогать нельзя.
_START = r'(^|[.!?]\s+|\n\s*|[•\-–—]\s+|\bя\s+)'
# Между началом и глаголом помещается «ничего не», «пока не», «уже»:
# «Ничего не нашёл» — про себя, а подлежащего в такой фразе нет
_FILLER = (r'((?:(?:ничего|никого|ничем|пока|уже|тут|сама|просто|всё|все|ещё|еще)'
           r'\s+)*(?:не\s+)?)')

_SELF = re.compile(_START + _FILLER + r'([«"*_]*)(' + _ANY + r')\b',
                   re.IGNORECASE | re.MULTILINE)


def fix(text: str) -> str:
    """Приводит рассказ о себе к женскому роду."""
    if not text:
        return text
    return _SELF.sub(
        lambda m: m.group(1) + m.group(2) + m.group(3) + _female(m.group(4)), text)
