"""Брань в расшифровках — сетка безопасности.

Сантехник на объекте говорит как говорит, и это нормально. Ненормально,
когда его слова дословно ложатся в паспорт дома, в выгрузку инженеру и в
отчёт, который откроет руководитель.

Основную работу делает модель: она пересказывает отчёт деловым языком.
Но указание она держит не всегда, а расшифровка сохраняется в базу —
поэтому здесь второй рубеж, уже без всякого ИИ.

Список корней намеренно короткий и строгий. Ложное срабатывание здесь
дороже пропуска: замазать «щебень» или «требуется» хуже, чем пропустить
редкое ругательство.
"""
import re

# Формы перечислены целиком, а не корнями с любым началом: приставочный
# поиск ловит «требуется» и «щебень», а это обычные рабочие слова
FORMS = [
    r'ху[йиеёя]\w*', r'\w{0,4}хуй\w*', r'нахуй', r'похуй', r'офиге\w*',
    r'\w{0,3}пизд\w*', r'пиздец\w*',
    r'[её]бан\w*', r'[её]бат\w*', r'[её]бал\w*', r'[её]буч\w*', r'[её]бен\w*',
    r'[её]бну\w*', r'[её]бн[уеё]\w*', r'[её]бы\w*',
    r'за[её]б\w*', r'на[её]б\w*', r'у[её]б\w*', r'до[её]б\w*', r'об[ъь]?[её]б\w*',
    r'раз[ъь]?[её]б\w*', r'про[её]б\w*', r'с[ъь]?[её]б\w*', r'вы[её]б\w*',
    r'бля\w*', r'блэ\w*',
    r'сук[аиуе]\b', r'сукин\w*', r'сучар\w*',
    r'муд[аои]к\w*', r'мудил\w*',
    r'пид[оа]р\w*', r'г[оа]ндон\w*', r'залуп\w*', r'дроч\w*',
    r'манд[ауые]\b',
    r'херн\w*', r'нахер\w*', r'нахрен\w*',
]

PATTERN = re.compile(r'(?<![а-яё])(?:' + '|'.join(FORMS) + r')(?![а-яё])',
                     re.IGNORECASE)

ZAMENA = '[…]'


def has_mat(text: str) -> bool:
    return bool(text) and bool(PATTERN.search(text))


def mask(text: str) -> str:
    """Убирает брань из текста, который увидят люди и документы."""
    if not text:
        return text
    # Двойные пробелы и «висящие» знаки после вырезания — тоже мусор
    out = PATTERN.sub(ZAMENA, text)
    out = re.sub(r'(?:\s*\[…\]){2,}', ' […]', out)
    out = re.sub(r'[ \t]{2,}', ' ', out)
    return out.strip()
