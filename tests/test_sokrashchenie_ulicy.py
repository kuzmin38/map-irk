"""Сокращённое название улицы в отчёте — «Кр. Мад.» — должно узнаваться.

Татьяна Григорьевна написала в «Обслуживание»: «СРОЧНО Кр. Мад. 14 над
17 квартирой течь с балкона по стояку топит всех». Заказчик спросил,
сохранила ли это Люся в карточку дома 14 — и она не сохранила: корневое
сравнение улицы («Красных» / «Мадьяр» по первым буквам) не ловит
сокращение, оно вообще не похоже на полное название по буквам.

Голосовое в том же инциденте («14 дом Красных Мадьяр, есть такое дело,
льёт») распозналось верно — модель произнесла название полностью. А вот
короткая текстовая заявка, написанная второпях, — нет. Люди в спешке
пишут именно так, и это не редкий случай, а обычный.
"""
import pytest

from bot import houses


def dom(address):
    return next(h for h in houses.HOUSES if h['address'] == address)


@pytest.mark.parametrize('text', [
    'СРОЧНО   Кр. Мад.  14 над 17 квартирой течь с балкона по стояку топит всех.',
    'Кр Мад 14 подвал топит',
    'КрМад 14 авария',
    'кр.мад. 14 течь',
])
def test_sokrashchenie_uznayotsya(text):
    h = houses.detect_house(text)
    assert h is not None, f'не нашла дом в «{text}»'
    assert h['address'] == 'Красных Мадьяр 14'


def test_polnoe_nazvanie_po_prezhnemu_rabotaet():
    """Правка не должна сломать то, что уже работало."""
    h = houses.detect_house('14 дом Красных Мадьяр, есть такое дело, льёт')
    assert h and h['address'] == 'Красных Мадьяр 14'


def test_ne_putaet_s_drugimi_ulicami():
    """«Кр.» не должно цеплять что-то постороннее — в справочнике такая
    улица одна, но проверяем явно, чтобы регрессия была видна сразу."""
    for h in houses.HOUSES:
        if h['address'] == 'Красных Мадьяр 14':
            continue
        assert 'Кр. Мад.' not in (h.get('aliases') or [])
