"""Люся — она. О себе пишет в женском роде.

Заказчик увидел в чате «Понял, переписываю» и «Записал». В подсказке модели
это сказано прямо, но держится указание через раз, поэтому готовый ответ
правим сами.
"""
import pytest

from bot.feminine import fix


@pytest.mark.parametrize('bylo, stalo', [
    ('Понял, переписываю:', 'Поняла, переписываю:'),
    ('Записал.', 'Записала.'),
    ('Нашёл два дома', 'Нашла два дома'),
    ('Готов помочь!', 'Готова помочь!'),
    ('Я не понял вопрос', 'Я не поняла вопрос'),
    ('Я уже посмотрел заявки', 'Я уже посмотрела заявки'),
    ('Ничего не нашёл по этому адресу.', 'Ничего не нашла по этому адресу.'),
    ('Проверил. Записал в паспорт.', 'Проверила. Записала в паспорт.'),
    ('• Проверил заявки', '• Проверила заявки'),
    ('**Записал** в паспорт', '**Записала** в паспорт'),
])
def test_o_sebe_v_zhenskom_rode(bylo, stalo):
    assert fix(bylo) == stalo


@pytest.mark.parametrize('chuzhie_slova', [
    'Виталя записал показания, а мастер посмотрел стояк',
    'Сантехник Константин закрыл заявку',
    'Он сделал всё сам',
    'Инженер сказал, что готов принять узел',
    'Слесарь пришёл и записал показания',
])
def test_o_drugih_lyudyah_ne_trogaet(chuzhie_slova):
    """«Виталя записала» было бы хуже исходной ошибки."""
    assert fix(chuzhie_slova) == chuzhie_slova


def test_uzhe_zhenskiy_rod_ne_portitsya():
    text = 'Записала — всё на месте. Проверила паспорт, нашла два дома.'
    assert fix(text) == text


def test_pustaya_stroka():
    assert fix('') == ''
    assert fix(None) is None
